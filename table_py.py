def random_text(min_words=3, max_words=15):
    words = ["доставка", "еда", "сервис", "приложение", "интерфейс", "ресторан", "продукты", "заказ",
             "вкусно", "быстро", "удобно", "качество", "цена", "ассортимент", "рекомендации", "поиск"]
    return ' '.join(random.choices(words, k=random.randint(min_words, max_words)))

def generate_data(num_rows):
    data = []
    start_date = datetime(2025, 6, 1)
    end_date = datetime(2025, 6, 14, 23, 59, 59)
    
    for _ in range(num_rows):
        # Генерация временной метки
        time_delta = random.random() * (end_date - start_date)
        timestamp = (start_date + time_delta).strftime("%d.%m.%Y %H:%M:%S")
        
        row = [
            timestamp,
            random.choice(AGES),
            random.choice(CITIES),
            random.choice(FREQUENCIES),
            ', '.join(random.sample(SERVICES, k=random.randint(1, 3))),
            *[random.randint(1, 5) for _ in range(10)],  # 10 колонок приоритетов
            random.choice(PRICE_OPTIONS),
            random.choice(YES_NO),
            ', '.join(random.sample(ASSORTMENT_OPTIONS, k=random.randint(1, 4))),
            ', '.join(random.sample(USAGE_OPTIONS, k=random.randint(1, 5))),
            ', '.join(random.sample(PROBLEMS_OPTIONS, k=random.randint(1, 4))),
            random.choice(DELIVERY_FAIRNESS),
            random.choice(YES_NO),
            random.choice(AGREE_OPTIONS),
            random.randint(1, 5),
            random.choice(YES_NO),
            random.choice(YES_NO),
            random_text(3, 8) if random.random() < 0.3 else '-',
            random.choice(SUBSCRIPTION_OPINION),
            random.choice(DELIVERY_TIME_IMPORTANCE),
            random.choice(YES_NO),
            random.choice(YES_NO),
            random.choice(FREQUENCY_OPTIONS),
            random.choice(YES_NO),
            random.choice(MED_IMPORTANCE),
            random.choice(YES_NO),
            random.choice(BOXES_OPTIONS),
            random.choice(ABROAD_OPTIONS),
            random.choice(MED_IMPORTANCE),
            random.choice(PICKUP_OPTIONS),
            random.choice(GROUP_ORDER_OPTIONS),
            random.choice(YES_NO),
            random_text(4, 10) if random.random() < 0.2 else '-'
        ]
        data.append(row)
    
    return data

